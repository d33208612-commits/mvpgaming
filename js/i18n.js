  let currentLang = localStorage.getItem("kartix_lang") || "ru";
  if (!I18N[currentLang]) currentLang = "ru";

  function t(key) {
    const dict = I18N[currentLang] || I18N.ru;
    return dict[key] !== undefined ? dict[key] : (I18N.ru[key] !== undefined ? I18N.ru[key] : key);
  }

  function getLang() {
    return currentLang;
  }

  function setLang(lang) {
    if (!I18N[lang]) return;
    currentLang = lang;
    localStorage.setItem("kartix_lang", lang);
    document.documentElement.setAttribute("lang", lang);
    applyTranslations();
    document.dispatchEvent(new CustomEvent("languagechange", { detail: { lang } }));
  }

  function applyTranslations(root) {
    const scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    scope.querySelectorAll("[data-i18n-html]").forEach((el) => {
      el.innerHTML = t(el.getAttribute("data-i18n-html"));
    });
    scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    scope.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
    });
  }

  window.I18N = { t, getLang, setLang, applyTranslations, dict: I18N };
