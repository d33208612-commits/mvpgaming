export const LANGS = [
  { value: 'ru', label: 'Русский', flag: '🇷🇺', short: 'RU' },
  { value: 'uz', label: 'O‘zbekcha', flag: '🇺🇿', short: 'UZ' },
];

function detectLang() {
  const saved = localStorage.getItem('lang');
  if (saved === 'ru' || saved === 'uz') return saved;
  const tgLang = window.Telegram?.WebApp?.initDataUnsafe?.user?.language_code;
  return tgLang === 'uz' ? 'uz' : 'ru';
}

const LangContext = createContext(null);
export const useLang = () => useContext(LangContext);

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(detectLang);

  const setLang = useCallback((next) => {
    setLangState(next);
    localStorage.setItem('lang', next);
    api.setLang(next).catch(() => {});
  }, []);

  const t = useCallback(
    (key, vars) => {
      let str = DICT[lang]?.[key] ?? DICT.ru[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) str = str.replaceAll(`{${k}}`, v);
      return str;
    },
    [lang]
  );

  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>;
}
